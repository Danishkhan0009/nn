#!/bin/bash
#==============================================================================
# FIDO V3 (WITCHER) SV kit - shared functions for the run scripts. Do not run directly.
#==============================================================================

fido_stamp() { date +%Y%m%d_%H%M%S; }

# new_run_dir <parent> <label>  -> creates and prints a unique run folder
fido_new_run_dir() {
  local parent=$1 label=$2 d n=1
  mkdir -p "$parent" || return 1
  d="$parent/$(fido_stamp)_$label"
  while [ -e "$d" ]; do n=$((n + 1)); d="$parent/$(fido_stamp)_${label}_$n"; done
  mkdir -p "$d" && echo "$d"
}

# fido_files <cfg> <A|B>  -> absolute source list, compile order
#   B : flist/rtl.f + rtl/cfg/fido_<cfg>.sv + flist/tb.f + tb/tb_<cfg>.sv
#   A : design/fido_<cfg>.sv + tb/tb_<cfg>.sv (generated by tools/build_optionA.py)
fido_flist() {
  sed -e 's#//.*##' -e '/^[[:space:]]*$/d' "$FIDO_ROOT/optionB_common/flist/$1" |
    sed "s#^#$FIDO_ROOT/optionB_common/#"
}
fido_files() {
  local c=$1 o=$2
  if [ "$o" = "B" ]; then
    echo $(fido_flist rtl.f) "$FIDO_ROOT/optionB_common/rtl/cfg/fido_$c.sv" \
         $(fido_flist tb.f)  "$FIDO_ROOT/optionB_common/tb/tb_$c.sv"
  else
    echo "$FIDO_ROOT/optionA_self_contained/design/fido_$c.sv $FIDO_ROOT/optionA_self_contained/tb/tb_$c.sv"
  fi
}

# fido_local_lib <dir> : run-local cds.lib and hdl.var.
# Without them Xcelium falls back to ~/cds.lib and ~/hdl.var, so stale entries
# there (e.g. a DEFINE to a folder that no longer exists -> *W,DLCPTH) leak
# into every run. The run folder gets its own, empty set; xrun defines worklib.
fido_local_lib() {
  local d=$1
  printf '%s\n' "# FIDO V3 SV run-local cds.lib - keeps ~/cds.lib out of this run." \
                 "# worklib is defined by xrun (-xmlibdirname)." > "$d/cds.lib"
  printf '%s\n' "# FIDO V3 SV run-local hdl.var - keeps ~/hdl.var out of this run." > "$d/hdl.var"
}

fido_check_cfg() {
  case "$1" in
    cg_fine|cg_coarse|pg_fine|pg_coarse) return 0 ;;
    cgpg_fine|cgpg_coarse|cgpg_ml_fine|cgpg_ml_coarse) return 0 ;;
    *) echo "unknown configuration '$1' (use: $FIDO_CFGS)" >&2; return 1 ;;
  esac
}

# fido_parse <log> <run_dir> : writes results.txt and results.csv from the
# testbench output inside the simulator log
fido_parse() {
  local log=$1 dir=$2
  awk '/FIDO V3 shared kit/ {on=1; print "==========================================================================="}
       on {print}
       /ALL TESTS PASSED|TESTS FAILED/ {if (on) {getline; print; on=0}}' "$log" > "$dir/results.txt"
  awk 'BEGIN { print "test,name,result,retired,ref_cycles,dut_cycles,overhead_pct,gating_stalls" }
       /^ T[0-9][0-9] / { id=$1; name=$2; ret=""; rc=""; dc=""; ov=""; st="" }
       /retired [0-9]+ instr/ { ret=$2; rc=$6; dc=$10; ov=$14; st=$19 }
       /RESULT T[0-9][0-9]/ { printf "%s,%s,%s,%s,%s,%s,%s,%s\n", id, name, $NF, ret, rc, dc, ov, st }' \
      "$log" > "$dir/results.csv"
}

# fido_run_one <sim:xrun|icarus> <cfg> <opt> <test> <seed> <waves> <gui> <verbose> <run_dir>
# Runs one configuration inside <run_dir>; prints a short report; returns
#   0 PASS  all tests passed, 0 checker errors, 0 tool errors, 0 tool warnings
#   3 WARN  as PASS but the simulator printed warnings (see tool_warnings.txt)
#   1 FAIL  anything else
fido_run_one() {
  local sim=$1 c=$2 o=$3 t=$4 s=$5 waves=$6 gui=$7 verb=$8 dir=$9
  local files plus="" log rc=0 nw=0 ne=0 passed=0 failed=0 chk=0 status
  files=$(fido_files "$c" "$o")
  for f in $files; do
    [ -f "$f" ] || { echo "missing source file: $f" >&2; return 1; }
  done
  [ -n "$t" ] && plus="$plus +TEST=$t"
  [ -n "$s" ] && plus="$plus +SEED=$s"
  [ "$verb" = "1" ] && plus="$plus +VERBOSE"
  [ -n "${FIDO_EXTRA_PLUS:-}" ] && plus="$plus $FIDO_EXTRA_PLUS"   # e.g. +MLTRACE (run_ml_train.sh)

  if [ "$sim" = "xrun" ]; then
    command -v xrun >/dev/null 2>&1 || {
      echo "xrun not found - expected in $XCELIUM_HOME/tools/bin" >&2
      fido_cadence_hint; return 1; }
    log="$dir/xrun.log"
    fido_local_lib "$dir"
    local libopt="-cdslib $dir/cds.lib -hdlvar $dir/hdl.var"
    local extra=""
    if [ "$waves" = "1" ] || [ "$gui" = "1" ]; then extra="$extra -access +rwc"; fi
    if [ "$waves" = "1" ]; then
      {
        echo "database -open waves -shm -into $dir/waves.shm -default"
        echo "probe -create -database waves tb_$c -all -depth all"
        echo "run"
        echo "exit"
      } > "$dir/waves.tcl"
      extra="$extra -input $dir/waves.tcl"
    fi
    [ "$gui" = "1" ] && extra="$extra -gui"
    # -sv            : all sources are SystemVerilog (IEEE 1800-2012)
    # -nowarn DSEMEL : Xcelium's notice that an SV design is simulated with the
    #                  IEEE 1800-2009 semantics (a tool notice, not about the code)
    local svopt="-sv -nowarn DSEMEL"
    echo "xrun -64bit -licqueue $svopt $libopt -xmlibdirname $dir/xcelium.d -top tb_$c $files $extra $plus -l $log" > "$dir/cmd.txt"
    xrun -version > "$dir/tool_version.txt" 2>&1
    # shellcheck disable=SC2086
    ( cd "$dir" && xrun -64bit -licqueue $svopt $libopt -xmlibdirname "$dir/xcelium.d" -top "tb_$c" \
        $files $extra $plus -l "$log" > "$dir/xrun.stdout" 2>&1 )
    rc=$?
    grep -E '\*W,[A-Z0-9]+' "$log" > "$dir/tool_warnings.txt" 2>/dev/null
    grep -E '\*[EF],[A-Z0-9]+' "$log" > "$dir/tool_errors.txt" 2>/dev/null
  else
    command -v iverilog >/dev/null 2>&1 || { echo "iverilog not found" >&2; return 1; }
    log="$dir/icarus.log"
    echo "iverilog -g2012 -Wall -o $dir/sim.vvp -s tb_$c $files ; vvp -n $dir/sim.vvp $plus" > "$dir/cmd.txt"
    iverilog -V 2>&1 | head -1 > "$dir/tool_version.txt"
    # shellcheck disable=SC2086
    ( cd "$dir" && iverilog -g2012 -Wall -o "$dir/sim.vvp" -s "tb_$c" $files > "$log" 2>&1 \
        && vvp -n "$dir/sim.vvp" $plus >> "$log" 2>&1 )
    rc=$?
    # Icarus 12 prints "sorry: constant selects in always_* processes ..." for
    # always_comb blocks (an Icarus limitation, not a design issue): ignored
    grep -iE 'warning' "$log" | grep -v 'constant selects in always_' > "$dir/tool_warnings.txt" 2>/dev/null
    grep -iE '(^|: )error|syntax error' "$log" > "$dir/tool_errors.txt" 2>/dev/null
  fi
  [ -s "$dir/tool_warnings.txt" ] || rm -f "$dir/tool_warnings.txt"
  [ -s "$dir/tool_errors.txt" ]   || rm -f "$dir/tool_errors.txt"
  [ -f "$dir/tool_warnings.txt" ] && nw=$(wc -l < "$dir/tool_warnings.txt")
  [ -f "$dir/tool_errors.txt" ]   && ne=$(wc -l < "$dir/tool_errors.txt")
  if [ "$sim" = "xrun" ] && [ -f "$dir/tool_errors.txt" ] && grep -qi 'licen' "$dir/tool_errors.txt"; then
    echo "  $c: Xcelium licence error (see $dir/tool_errors.txt)" >&2
    fido_cadence_hint
  fi

  fido_parse "$log" "$dir"
  local sum
  sum=$(grep -E ' SUMMARY ' "$log" | tail -1)
  if [ -n "$sum" ]; then
    passed=$(echo "$sum" | sed -E 's/.*: ([0-9]+) passed.*/\1/')
    failed=$(echo "$sum" | sed -E 's/.* ([0-9]+) failed.*/\1/')
    chk=$(echo "$sum" | sed -E 's/.* ([0-9]+) checker errors.*/\1/')
  fi
  if [ -n "$sum" ] && [ "$failed" = "0" ] && [ "$chk" = "0" ] && [ "$ne" = "0" ] && [ "$passed" != "0" ]; then
    if [ "$nw" = "0" ]; then status=PASS; else status=WARN; fi
  else
    status=FAIL
  fi
  echo "$status" > "$dir/STATUS"
  {
    echo "config        : $c (option $o, simulator $sim)"
    echo "tests         : ${t:-all}   seed: ${s:-default}"
    echo "passed/failed : $passed / $failed   checker errors: $chk"
    echo "tool messages : $nw warnings, $ne errors (simulator exit code $rc)"
    echo "status        : $status"
  } > "$dir/run_info.txt"

  # one line per run in the history file
  local hist="$FIDO_RUNS/history.csv"
  [ -f "$hist" ] || echo "timestamp,sim,cfg,opt,test,seed,passed,failed,checker_errors,tool_warnings,tool_errors,status,run_dir" > "$hist"
  echo "$(date '+%Y-%m-%d %H:%M:%S'),$sim,$c,$o,${t:-all},${s:-1},$passed,$failed,$chk,$nw,$ne,$status,${dir#$FIDO_RUNS/}" >> "$hist"

  printf "  %-15s opt %s  %-4s  passed %2s  failed %2s  checker %2s  tool-warn %3s  tool-err %3s  -> %s\n" \
    "$c" "$o" "$status" "$passed" "$failed" "$chk" "$nw" "$ne" "${dir#$FIDO_ROOT/}"
  case "$status" in PASS) return 0 ;; WARN) return 3 ;; *) return 1 ;; esac
}

fido_link_latest() {
  ln -sfn "$1" "$FIDO_RUNS/latest" 2>/dev/null
}
