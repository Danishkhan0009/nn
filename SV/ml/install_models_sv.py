#!/usr/bin/env python3
# =============================================================================
# FIDO V3 (WITCHER) SV kit - install trained ML models into the SV tree.
#
#   python3 ml/install_models_sv.py <models file> <SV kit root> [backup dir]
#
# <models file> : any file holding the "ML MODELS BEGIN ... END" section written
#                 by ml/train_ml.py (ml_models.v from run_ml_train.sh, or the
#                 Verilog kit's fido_common.v).
# Writes        : optionB_common/rtl/ml_export/ml_models_fine.sv
#                 optionB_common/rtl/ml_export/ml_models_coarse.sv
# and then rebuilds every Option A file (tools/build_optionA.py), so both
# layouts always carry the same models. Old files are copied to [backup dir].
# =============================================================================
import os
import re
import shutil
import subprocess
import sys

BEGIN = "// ==== ML MODELS BEGIN"
END = "// ==== ML MODELS END ===="

HEAD = """//=============================================================================
// FIDO V3 (WITCHER) - SystemVerilog RTL
// File      : rtl/ml_export/{name}.sv
// Module    : {name}
// Content   : exported power-gating policies ({grain} grain), one per power
//             domain. GENERATED by ml/train_ml.py and installed by
//             ml/install_models_sv.py - do not edit by hand.
//             Input : 8 feature slots x 32 bit (see ml_feature_block).
//             Output: dec[3*d +: 3] = {{confidence, class}}; class 1 = stay
//             (CG only), 2 = power off with retention, 3 = power off. The
//             safety shell accepts a power-gating request only with
//             confidence 1.
//             {note}
// Hierarchy : fido_top > u_pmu > g_dual.g_model_{g}.u_models (MODE 4 only)
// Language  : SystemVerilog IEEE 1800-2012, target Cadence Xcelium 22.09
//=============================================================================
`timescale 1ns/1ps
`default_nettype none

"""
TAIL = "\n`default_nettype wire\n"


def extract(text, name):
    m = re.search(r"^module %s \(.*?^endmodule" % name, text, re.S | re.M)
    if not m:
        sys.exit("module %s not found in the ML MODELS section" % name)
    body = m.group(0)
    body = body.replace("endmodule", "endmodule : %s" % name)
    return body + "\n"


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: install_models_sv.py <models file> <SV kit root> [backup dir]")
    src = open(sys.argv[1]).read()
    b = src.find(BEGIN)
    e = src.find(END)
    if b < 0 or e < b:
        sys.exit("no ML MODELS section in %s" % sys.argv[1])
    sect = src[b:e]
    nm = re.search(r"^// (trained on .*|UNTRAINED.*)$", sect, re.M)
    note = nm.group(1) if nm else ""
    root = sys.argv[2]
    bdir = sys.argv[3] if len(sys.argv) > 3 else None
    odir = os.path.join(root, "optionB_common", "rtl", "ml_export")
    os.makedirs(odir, exist_ok=True)
    for name, grain, g in (("ml_models_fine", "fine", "f"), ("ml_models_coarse", "coarse", "c")):
        out = os.path.join(odir, name + ".sv")
        if bdir and os.path.exists(out):
            os.makedirs(bdir, exist_ok=True)
            shutil.copy2(out, os.path.join(bdir, name + ".sv"))
        with open(out, "w") as fh:
            fh.write(HEAD.format(name=name, grain=grain, g=g, note=note) + extract(sect, name) + TAIL)
        print("  wrote %s" % os.path.relpath(out, root))
    tool = os.path.join(root, "tools", "build_optionA.py")
    if os.path.exists(tool):
        subprocess.check_call([sys.executable, tool, root])
    print("models installed")


if __name__ == "__main__":
    main()
