#!/usr/bin/env python3
# =============================================================================
# FIDO V3 (WITCHER) SV kit - build Option A (self-contained files) from the
# Option B source tree.
#
#   python3 tools/build_optionA.py [SV kit root]
#
# For every configuration <cfg>:
#   optionA_self_contained/design/fido_<cfg>.sv = flist/rtl.f files + rtl/cfg/fido_<cfg>.sv
#   optionA_self_contained/tb/tb_<cfg>.sv       = flist/tb.f files  + tb/tb_<cfg>.sv
# in file-list order (packages first). Option A therefore always holds exactly
# the same code as Option B. Never edit Option A by hand - edit optionB_common/
# and run this script (ml/install_models_sv.py runs it automatically).
# =============================================================================
import os
import sys

CFGS = ["cg_fine", "cg_coarse", "pg_fine", "pg_coarse",
        "cgpg_fine", "cgpg_coarse", "cgpg_ml_fine", "cgpg_ml_coarse"]

BANNER = """//=============================================================================
// FIDO V3 (WITCHER) - SystemVerilog, OPTION A (self-contained)
// File      : {rel}
// Content   : {what} of configuration {cfg}, one file.
//             GENERATED by tools/build_optionA.py from optionB_common/
//             (files below, in compile order) - do not edit by hand.
// Compile   : xrun -sv design/fido_{cfg}.sv tb/tb_{cfg}.sv -top tb_{cfg}
//             (compile ONE design file per run: two Option A design files
//              together would define every module twice)
// Sources   :
{srcs}
//=============================================================================

"""


def flist(root, name):
    path = os.path.join(root, "optionB_common", "flist", name)
    out = []
    for line in open(path):
        line = line.strip()
        if line and not line.startswith("//"):
            out.append(line)
    return out


def build(root, rel_out, what, cfg, files):
    b = os.path.join(root, "optionB_common")
    srcs = "\n".join("//               %s" % f for f in files)
    parts = [BANNER.format(rel=rel_out, what=what, cfg=cfg, srcs=srcs)]
    for f in files:
        txt = open(os.path.join(b, f)).read().rstrip("\n") + "\n"
        parts.append("// ---------------------------------------------------------------------------\n"
                     "// >>> %s\n"
                     "// ---------------------------------------------------------------------------\n" % f)
        parts.append(txt)
        parts.append("\n")
    out = os.path.join(root, "optionA_self_contained", rel_out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("".join(parts).rstrip("\n") + "\n")


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    rtl = flist(root, "rtl.f")
    tb = flist(root, "tb.f")
    for c in CFGS:
        build(root, "design/fido_%s.sv" % c, "design (shared RTL + configuration top)", c,
              rtl + ["rtl/cfg/fido_%s.sv" % c])
        build(root, "tb/tb_%s.sv" % c, "testbench (shared environment + testbench top)", c,
              tb + ["tb/tb_%s.sv" % c])
    print("  Option A rebuilt: %d design + %d testbench files" % (len(CFGS), len(CFGS)))


if __name__ == "__main__":
    main()
